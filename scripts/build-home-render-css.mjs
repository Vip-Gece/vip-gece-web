import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { parse, serialize } from "parse5";

import CleanCSS from "clean-css";
import { PurgeCSS } from "purgecss";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "public/css/home-render.min.css");
const require = createRequire(import.meta.url);

const CSS_FILES = [
  "style.css",
  "public/css/icons.css",
  "public/css/components.css",
  "public/css/home-redesign.css"
];

const CONTENT_FILES = [
  "public/js/home/search.js",
  "public/js/deferred-css.js"
];

function markupOnly(html) {
  const document = parse(html);
  function strip(node) {
    node.childNodes = (node.childNodes || []).filter(child => !["style", "script"].includes(child.tagName));
    for (const child of node.childNodes) strip(child);
  }
  strip(document);
  return serialize(document);
}

// Scan the actual SSR surface, not source-only branches for removed hero panels.
const { renderHomeHtml } = require("../src/services/render/homeRenderer");
const fixtures = Array.from({ length: 16 }, (_, index) => ({
  id: `css-fixture-${index}`, slug: `css-fixture-${index}`, name: `Fixture ${index}`,
  city: "Istanbul", district: "Istanbul Geneli", type: index % 2 ? "vip" : "normal",
  is_active: true, normal_slot: index + 1, vip_slot: index + 1,
  images: index % 2 ? ["/logo.png.webp"] : [], age: index % 2 ? 25 : ""
}));

async function source(fileName) {
  return fs.readFile(path.join(ROOT, fileName), "utf8");
}

const css = await Promise.all(CSS_FILES.map(async (fileName) => {
  let raw = await source(fileName);
  if (fileName === "style.css") {
    raw = raw.replace(/\/\* Legacy ad shells[\s\S]*$/i, "").trim();
  }
  return { raw };
}));

const content = await Promise.all(CONTENT_FILES.map(async (fileName) => ({
  raw: await source(fileName),
  extension: path.extname(fileName).slice(1)
})));
content.push({ raw: markupOnly(renderHomeHtml(fixtures)), extension: "html" });
content.push({ raw: markupOnly(renderHomeHtml([])), extension: "html" });

const purged = await new PurgeCSS().purge({
  content,
  css,
  safelist: {
    standard: [
      "active",
      "is-active",
      "is-marquee",
      "is-paused",
      "search-drawer-open"
    ]
  }
});

const optimized = new CleanCSS({
  level: 2,
  rebase: false
}).minify(purged.map((item) => item.css).join("\n"));

if (optimized.errors.length) {
  throw new Error(`Home CSS build failed: ${optimized.errors.join("; ")}`);
}

const banner = "/* Generated by npm run build:home-css. Do not edit directly. */\n";
await fs.writeFile(OUTPUT, `${banner}${optimized.styles}\n`, "utf8");

console.log(`home_css=${path.relative(ROOT, OUTPUT)}`);
console.log(`source_bytes=${css.reduce((total, item) => total + item.raw.length, 0)}`);
console.log(`output_bytes=${banner.length + optimized.styles.length + 1}`);
