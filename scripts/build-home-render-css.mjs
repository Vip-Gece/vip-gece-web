import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import CleanCSS from "clean-css";
import { PurgeCSS } from "purgecss";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "public/css/home-render.min.css");

const CSS_FILES = [
  "style.css",
  "public/css/icons.css",
  "public/css/components.css",
  "public/css/home-redesign.css"
];

const CONTENT_FILES = [
  "index.html",
  "src/services/render/homeRenderer.js",
  "src/services/render/shared.js",
  "public/components/header.html",
  "public/components/footer.html",
  "public/components/mobile-nav.html",
  "public/components/language.html",
  "public/js/components-loader.js",
  "public/js/home/index.js",
  "public/js/home/search.js"
];

async function source(fileName) {
  return fs.readFile(path.join(ROOT, fileName), "utf8");
}

const css = await Promise.all(CSS_FILES.map(async (fileName) => {
  let raw = await source(fileName);
  if (fileName === "style.css") {
    raw = raw.replace(/\/\* Legacy ad shells[\s\S]*$/i, "").trim();
  }
  return { raw };
}));

const content = await Promise.all(CONTENT_FILES.map(async (fileName) => ({
  raw: await source(fileName),
  extension: path.extname(fileName).slice(1)
})));

const purged = await new PurgeCSS().purge({
  content,
  css,
  safelist: {
    standard: [
      "active",
      "is-active",
      "is-marquee",
      "is-paused",
      "search-drawer-open"
    ]
  }
});

const optimized = new CleanCSS({
  level: 2,
  rebase: false
}).minify(purged.map((item) => item.css).join("\n"));

if (optimized.errors.length) {
  throw new Error(`Home CSS build failed: ${optimized.errors.join("; ")}`);
}

const banner = "/* Generated by npm run build:home-css. Do not edit directly. */\n";
await fs.writeFile(OUTPUT, `${banner}${optimized.styles}\n`, "utf8");

console.log(`home_css=${path.relative(ROOT, OUTPUT)}`);
console.log(`source_bytes=${css.reduce((total, item) => total + item.raw.length, 0)}`);
console.log(`output_bytes=${banner.length + optimized.styles.length + 1}`);
